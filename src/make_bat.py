# -*- coding: utf-8 -*-
# 生成 build.bat（GBK 编码供 cmd 使用）
# 位置：<产品>\src\build.bat；源码 = 本目录；工作区 = %TEMP%\KrakenAV_build（ASCII）
# 编译器：优先 PATH 中的 g++/windres（开源贡献者友好），回退本机 MinGW 路径
lines = [
    '@echo off',
    'rem ============================================================',
    'rem  KrakenAV build script',
    'rem  Sources = this directory; ASCII workdir = %%TEMP%%\\KrakenAV_build',
    'rem  Usage: build.bat [deploy-dir]  (default: parent of this directory)',
    'rem ============================================================',
    'setlocal',
    'set GCC=D:\\AZML\\mingw64\\bin\\g++.exe',
    'set WINDRES=D:\\AZML\\mingw64\\bin\\windres.exe',
    'where g++ >nul 2>nul && set GCC=g++',
    'where windres >nul 2>nul && set WINDRES=windres',
    'set SRCDIR=%~dp0',
    'set WORK=%TEMP%\\KrakenAV_build',
    'set DEPLOY=%~dp0..',
    '',
    'rem -- 1) Mirror sources to the ASCII workdir (MinGW ld cannot read non-ASCII paths) --',
    'if not exist "%WORK%" mkdir "%WORK%"',
    'robocopy "%SRCDIR%src" "%WORK%\\src" /MIR /NFL /NDL /NJH /NJS >nul',
    'robocopy "%SRCDIR%sdk" "%WORK%\\sdk" /MIR /NFL /NDL /NJH /NJS >nul',
    'if not exist "%WORK%\\src\\krakenav.ico" python "%SRCDIR%src\\make_icon.py" "%WORK%\\src"',
    '',
    'rem -- 2) Compile --',
    'cd /d "%WORK%"',
    'if not exist src\\app.res %WINDRES% src\\app.rc -O coff -o src\\app.res || goto :fail',
    '%GCC% -std=c++17 -municode -mwindows -O2 -static -Wall ^',
    '  -Isdk\\include -Isdk\\stubinc ^',
    '  src\\common.cpp src\\engine.cpp src\\updater.cpp src\\settingsui.cpp src\\draw.cpp src\\main.cpp ^',
    '  src\\app.res sdk\\clamav.lib ^',
    '  -lgdiplus -lshlwapi -lole32 -lshell32 -luuid -lgdi32 -luser32 -lcomctl32 -ladvapi32 ^',
    '  -o KrakenAV.exe || goto :fail',
    '%GCC% -std=c++17 -municode -O2 -static -Isdk\\include -Isdk\\stubinc ^',
    '  src\\common.cpp src\\engine.cpp src\\test_console.cpp sdk\\clamav.lib ^',
    '  -lshlwapi -lole32 -lshell32 -luuid -ladvapi32 -o test_console.exe || goto :fail',
    '%GCC% -std=c++17 -municode -O2 -static -Isdk\\include -Isdk\\stubinc ^',
    '  src\\common.cpp src\\quarantine_tool.cpp ^',
    '  -lshlwapi -lole32 -lshell32 -luuid -ladvapi32 -o quarantine_restore.exe || goto :fail',
    'echo [OK] built KrakenAV.exe + test_console.exe + quarantine_restore.exe',
    '',
    'rem -- 3) Deploy --',
    'if not "%~1"=="" set DEPLOY=%~1',
    'copy /y KrakenAV.exe "%DEPLOY%\\KrakenAV.exe" >nul || goto :fail',
    'copy /y test_console.exe "%DEPLOY%\\test_console.exe" >nul',
    'copy /y quarantine_restore.exe "%DEPLOY%\\quarantine_restore.exe" >nul',
    'echo [OK] deployed to %DEPLOY%',
    'exit /b 0',
    '',
    ':fail',
    'echo [FAIL] build error',
    'exit /b 1',
]
open(r'D:\Zcode\杀毒软件\KrakenAV\src\build.bat', 'w', encoding='gbk', newline='\r\n').write('\n'.join(lines) + '\n')
print('build.bat written')
